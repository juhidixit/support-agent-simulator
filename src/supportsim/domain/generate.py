"""Deterministic generator for the synthetic Aster Bank database.

All people, addresses and transactions are fictional and produced from a fixed
seed, so the committed ``bank_db.json`` can be regenerated byte-for-byte::

    python -m supportsim.domain.generate --out src/supportsim/data/bank_db.json
"""

from __future__ import annotations

import argparse
import json
import random
from datetime import date, timedelta
from pathlib import Path

from supportsim.domain.models import TODAY

FIRST = [
    "Ava", "Liam", "Maya", "Noah", "Priya", "Ethan", "Sofia", "Lucas", "Aisha", "Mateo",
    "Chloe", "Arjun", "Hana", "Diego", "Grace", "Omar", "Zoe", "Kenji", "Lena", "Samuel",
    "Nora", "Ravi", "Isla", "Felix", "Mia", "Jonah", "Elena", "Tariq", "Ruby", "Hugo",
    "Leah", "Kofi", "Ines", "Caleb", "Yara", "Owen", "Mei", "Victor", "Tess", "Amir",
]
LAST = [
    "Patel", "Nguyen", "Garcia", "Kim", "Okafor", "Silva", "Schmidt", "Rossi", "Cohen", "Haddad",
    "Moreau", "Tanaka", "Johansson", "Reyes", "Novak", "Mensah", "Fischer", "Costa", "Ibrahim",
    "Larsen", "Bennett", "Sato", "Kowalski", "Murphy", "Dubois", "Alvarez", "Chen", "Walsh",
]
STREETS = ["Maple Ave", "Harbor St", "Cedar Ln", "Elm St", "Ridge Rd", "Willow Way", "Lake Dr",
           "Pine Ct"]
CITIES = [
    ("Hoboken", "NJ", "07030"), ("Jersey City", "NJ", "07302"), ("Austin", "TX", "78704"),
    ("Denver", "CO", "80203"), ("Seattle", "WA", "98103"), ("Chicago", "IL", "60614"),
    ("Raleigh", "NC", "27601"), ("Portland", "OR", "97209"), ("Boston", "MA", "02116"),
]
MERCHANTS = [
    ("Corner Grocer", "groceries", (12, 140)), ("FreshMart", "groceries", (20, 180)),
    ("Metro Transit", "transport", (3, 60)), ("RideNow", "transport", (8, 55)),
    ("Bluebird Cafe", "dining", (5, 40)), ("Luigi's Trattoria", "dining", (30, 160)),
    ("StreamBox", "subscription", (9, 23)), ("CloudDrive Plus", "subscription", (3, 12)),
    ("TechHub Electronics", "electronics", (60, 1400)), ("Gadget Outlet", "electronics", (25, 600)),
    ("SkyWays Airlines", "travel", (120, 900)), ("Harborview Hotel", "travel", (140, 620)),
    ("QuickFuel", "fuel", (25, 90)), ("PetPals", "pets", (15, 120)),
    ("Urban Threads", "shopping", (20, 260)), ("HomeNest", "shopping", (35, 480)),
]
FEES = [("Overdraft fee", 35.0), ("Foreign transaction fee", 12.5), ("Late payment fee", 29.0),
        ("ATM fee", 3.5)]


def _phone(rng: random.Random) -> str:
    return f"{rng.randint(201, 989)}-555-{rng.randint(1000, 9999):04d}"


def generate(seed: int = 7, n_customers: int = 40) -> dict:
    rng = random.Random(seed)
    db: dict = {"customers": {}, "accounts": {}, "cards": {}, "transactions": {},
                "disputes": {}, "handoffs": []}
    txn_counter = 1000
    used_names: set[tuple[str, str]] = set()
    for i in range(n_customers):
        while True:
            first, last = rng.choice(FIRST), rng.choice(LAST)
            if (first, last) not in used_names:
                used_names.add((first, last))
                break
        cid = f"C{1001 + i}"
        city, state, zip_code = rng.choice(CITIES)
        dob = date(rng.randint(1958, 2003), rng.randint(1, 12), rng.randint(1, 28))
        tier = "premium" if rng.random() < 0.35 else "standard"
        waivers = []
        if rng.random() < 0.4:
            waivers.append((TODAY - timedelta(days=rng.randint(20, 300))).isoformat())
        db["customers"][cid] = {
            "customer_id": cid,
            "name": f"{first} {last}",
            "email": f"{first.lower()}.{last.lower()}@example.com",
            "phone": _phone(rng),
            "dob": dob.isoformat(),
            "address": {"street": f"{rng.randint(10, 999)} {rng.choice(STREETS)}",
                        "city": city, "state": state, "zip": zip_code},
            "tier": tier,
            "fee_waivers": waivers,
        }
        acct_id = f"A{2001 + i}"
        db["accounts"][acct_id] = {"account_id": acct_id, "customer_id": cid, "type": "checking",
                                   "balance": round(rng.uniform(150, 9000), 2)}
        n_cards = 2 if rng.random() < 0.45 else 1
        for k in range(n_cards):
            card_id = f"K{3001 + 2 * i + k}"
            kind = "debit" if k == 0 else "credit"
            db["cards"][card_id] = {"card_id": card_id, "customer_id": cid, "account_id": acct_id,
                                    "type": kind, "last4": f"{rng.randint(0, 9999):04d}",
                                    "status": "active"}
            for _ in range(rng.randint(8, 14)):
                merchant, category, (lo, hi) = rng.choice(MERCHANTS)
                days_ago = rng.randint(0, 120)
                txn_counter += 1
                tid = f"T{txn_counter}"
                db["transactions"][tid] = {
                    "transaction_id": tid, "card_id": card_id, "account_id": acct_id,
                    "date": (TODAY - timedelta(days=days_ago)).isoformat(),
                    "merchant": merchant, "category": category,
                    "amount": round(rng.uniform(lo, hi), 2),
                    "status": "pending" if days_ago <= 2 else "posted",
                    "disputed": False, "waived": False,
                }
            if kind == "debit":
                for _ in range(rng.randint(0, 2)):
                    name, amt = rng.choice(FEES)
                    txn_counter += 1
                    tid = f"T{txn_counter}"
                    db["transactions"][tid] = {
                        "transaction_id": tid, "card_id": card_id, "account_id": acct_id,
                        "date": (TODAY - timedelta(days=rng.randint(3, 150))).isoformat(),
                        "merchant": f"Aster Bank {name}", "category": "fee", "amount": amt,
                        "status": "posted", "disputed": False, "waived": False,
                    }
    # A few cards are already frozen and a few transactions already disputed.
    card_ids = sorted(db["cards"])
    for cid in rng.sample(card_ids, 4):
        db["cards"][cid]["status"] = "frozen"
    posted = sorted(t for t, v in db["transactions"].items()
                    if v["status"] == "posted" and v["category"] != "fee")
    for tid in rng.sample(posted, 5):
        t = db["transactions"][tid]
        t["disputed"] = True
        did = f"D-{tid}"
        db["disputes"][did] = {"dispute_id": did, "transaction_id": tid, "reason": "not_received",
                               "status": "open", "provisional_credit": False}
    return db


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="src/supportsim/data/bank_db.json")
    ap.add_argument("--seed", type=int, default=7)
    args = ap.parse_args()
    db = generate(args.seed)
    Path(args.out).write_text(json.dumps(db, indent=1, sort_keys=True) + "\n")
    print(f"wrote {args.out}: {len(db['customers'])} customers, {len(db['cards'])} cards, "
          f"{len(db['transactions'])} transactions")


if __name__ == "__main__":
    main()
